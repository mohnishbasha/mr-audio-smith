#!/usr/bin/env python3
"""Regenerate or verify the dependency tables in THIRD_PARTY_LICENSES.md (S6-T03, NFR-008).

Usage:
    python scripts/check-licenses.py            # rewrite the generated sections
    python scripts/check-licenses.py --check    # fail on a missing, unknown, or denied license

Python runtime dependencies come from `pip-licenses --format=json --with-urls` over the
installed environment, restricted to the runtime closure (every extra except `dev`, taken from
`uv export`). npm packages come from `npx license-checker --json --production`, falling back to
`npm ls --all --omit=dev --json` plus each package.json when license-checker is unavailable.
The hand-written "Model weights", "Bundled assets", and note sections are never touched.

Policy (enforced by --check):
    * every installed runtime dependency must have a row in the file,
    * its license must be known (override table below for packages with broken metadata),
    * AGPL, SSPL, and GPL-3.0 (only or later) are denied unless the package is in ALLOWLIST,
      which records why the copyleft code is acceptable.
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LICENSES_FILE = ROOT / "THIRD_PARTY_LICENSES.md"
PYPROJECT = ROOT / "pyproject.toml"
PY_HEADING = "## Python runtime dependencies"
NPM_HEADING = "## npm packages"
NPM_PROJECTS = ("player", "web/studio")
OWN_NPM_SCOPE = "@mr-audio-smith/"
DEV_EXTRAS = frozenset({"dev"})
UNKNOWN = "UNKNOWN"
MAX_LICENSE_CHARS = 80
SUBPROCESS_TIMEOUT_S = 300.0
TABLE_HEADER = "| Package | Version | License | URL |\n|---|---|---|---|"
GENERATED_NOTE = "<!-- generated by scripts/check-licenses.py; edit the script, not this table -->"

# Licenses that fail --check for runtime dependencies (matched case-insensitively).
DENY_PATTERNS = (
    re.compile(r"AGPL|AFFERO", re.IGNORECASE),
    re.compile(r"\bSSPL\b", re.IGNORECASE),
    re.compile(r"(?<![A-Z])GPL[-_ ]?V?3|GENERAL PUBLIC LICENSE V3", re.IGNORECASE),
)

# Denied licenses that are accepted, with the reason. Key: normalized package name.
ALLOWLIST: dict[str, str] = {
    "phonemizer-fork": (
        "GPL-3.0-or-later; pulled in only by the optional `kokoro` extra via misaki. Installed by the "
        "user's package manager, never vendored or bundled in our wheel or sdist."
    ),
    "pykakasi": (
        "GPL-3.0-or-later; pulled in only by the optional `chatterbox` extra via chatterbox-tts. "
        "Installed by the user's package manager, never vendored or bundled."
    ),
    "espeakng-loader": (
        "MIT loader that ships the espeak-ng library (GPL-3.0-or-later); pulled in only by the "
        "optional `kokoro` extra via misaki. Not redistributed by this project."
    ),
}

# Packages whose metadata carries no usable license (applied only while the metadata says UNKNOWN).
# Key: normalized name -> license text.
# TODO(mohinish): confirm each entry against the upstream repository (issue #52).
LICENSE_OVERRIDES: dict[str, str] = {
    # torch 2.15 wheels ship license metadata pip-licenses reports as UNKNOWN; upstream is BSD-3-Clause.
    "torch": "BSD-3-Clause",
    "espeakng-loader": "MIT (loader); bundles espeak-ng GPL-3.0-or-later",
}


@dataclass(frozen=True)
class Package:
    """One dependency row."""

    name: str
    version: str
    license: str
    url: str


def normalize_name(name: str) -> str:
    """PEP 503 normalization so `Jinja2`, `jinja2`, and `typing_extensions` compare equal."""
    return re.sub(r"[-_.]+", "-", name).lower()


def normalize_license(raw: str) -> str:
    """Collapse a license field to one short line; full license texts become their title line."""
    lines = [ln.strip() for ln in raw.strip().splitlines() if ln.strip()]
    if not lines:
        return UNKNOWN
    first = re.sub(r"\s+", " ", lines[0])
    if len(first) > MAX_LICENSE_CHARS:
        return UNKNOWN
    return first.replace("|", "/")


def parse_pip_licenses(text: str, runtime: set[str] | None) -> list[Package]:
    """Parse `pip-licenses --format=json --with-urls`, keeping only the runtime closure."""
    rows = json.loads(text)
    found: list[Package] = []
    for row in rows:
        key = normalize_name(row["Name"])
        if runtime is not None and key not in runtime:
            continue
        lic = normalize_license(row.get("License", ""))
        if lic == UNKNOWN:
            lic = LICENSE_OVERRIDES.get(key, UNKNOWN)
        found.append(Package(row["Name"], row["Version"], lic, row.get("URL") or UNKNOWN))
    return sorted(found, key=lambda p: normalize_name(p.name))


def split_npm_key(key: str) -> tuple[str, str]:
    """Split `@scope/name@1.2.3` into (name, version) on the last `@`."""
    name, _, version = key.rpartition("@")
    return name, version


def parse_license_checker(text: str) -> list[Package]:
    """Parse `license-checker --json`, dropping this repository's own packages."""
    found: list[Package] = []
    for key, info in json.loads(text).items():
        name, version = split_npm_key(key)
        if name.startswith(OWN_NPM_SCOPE):
            continue
        lic = info.get("licenses")
        lic_text = ", ".join(lic) if isinstance(lic, list) else str(lic or "")
        url = info.get("repository") or info.get("url") or f"https://www.npmjs.com/package/{name}"
        found.append(Package(name, version, normalize_license(lic_text), url))
    return found


def collect_ls_packages(tree: dict[str, object], found: dict[str, str]) -> None:
    """Walk an `npm ls --all --json` dependency tree, recording name -> version."""
    deps = tree.get("dependencies")
    if not isinstance(deps, dict):
        return
    for name, node in deps.items():
        if isinstance(node, dict):
            found.setdefault(name, str(node.get("version", "")))
            collect_ls_packages(node, found)


def package_from_manifest(project: Path, name: str, version: str) -> Package:
    """Read name's license from node_modules/<name>/package.json."""
    manifest = project / "node_modules" / name / "package.json"
    try:
        data = json.loads(manifest.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return Package(name, version, UNKNOWN, f"https://www.npmjs.com/package/{name}")
    lic = data.get("license") or data.get("licenses") or ""
    if isinstance(lic, dict):
        lic = lic.get("type", "")
    if isinstance(lic, list):
        lic = ", ".join(str(item.get("type", item)) if isinstance(item, dict) else str(item) for item in lic)
    repo = data.get("repository")
    url = repo.get("url") if isinstance(repo, dict) else repo
    return Package(
        name, version, normalize_license(str(lic)), str(url or f"https://www.npmjs.com/package/{name}")
    )


def run_tool(args: list[str], cwd: Path) -> str | None:
    """Run a tool, returning stdout or None when it is missing or fails."""
    if shutil.which(args[0]) is None:
        return None
    try:
        done = subprocess.run(
            args, cwd=cwd, capture_output=True, text=True, check=True, timeout=SUBPROCESS_TIMEOUT_S
        )
    except (subprocess.SubprocessError, OSError):
        return None
    return done.stdout


def npm_packages(project: Path) -> list[Package]:
    """Production npm packages for one project directory."""
    checked = run_tool(
        ["npx", "--yes", "license-checker", "--json", "--production", "--start", str(project)], ROOT
    )
    if checked:
        return parse_license_checker(checked)
    tree = run_tool(["npm", "ls", "--all", "--omit=dev", "--json"], project)
    found: dict[str, str] = {}
    if tree:
        collect_ls_packages(json.loads(tree), found)
    return [package_from_manifest(project, n, v) for n, v in sorted(found.items())]


def all_npm_packages() -> list[Package]:
    """Union over every npm project, one row per name and version."""
    merged: dict[tuple[str, str], Package] = {}
    for rel in NPM_PROJECTS:
        for pkg in npm_packages(ROOT / rel):
            merged[(pkg.name, pkg.version)] = pkg
    return sorted(merged.values(), key=lambda p: (p.name, p.version))


def runtime_extras() -> list[str]:
    """Every optional-dependency group except development tooling."""
    data = tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))
    return sorted(set(data.get("project", {}).get("optional-dependencies", {})) - DEV_EXTRAS)


def runtime_names() -> set[str] | None:
    """Names in the locked runtime closure (all non-dev extras), or None when uv is unavailable."""
    args = ["uv", "export", "--frozen", "--no-dev", "--no-emit-project", "--no-hashes"]
    for extra in runtime_extras():
        args += ["--extra", extra]
    out = run_tool(args, ROOT)
    if not out:
        return None
    names = {normalize_name(m.group(1)) for m in re.finditer(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==", out, re.M)}
    return names or None


# Runtime dependencies installed only on some platforms (keyring's Linux and Windows backends), so the
# inventory generated on one OS still covers the others. Versions are those in uv.lock.
PLATFORM_PACKAGES: tuple[Package, ...] = (
    Package("jeepney", "0.9.0", "MIT", "https://gitlab.com/takluyver/jeepney"),
    Package("SecretStorage", "3.5.0", "BSD-3-Clause", "https://github.com/mitya57/secretstorage"),
    Package("pywin32-ctypes", "0.2.3", "BSD-3-Clause", "https://github.com/enthought/pywin32-ctypes"),
)


def python_packages() -> list[Package]:
    """Installed runtime dependencies with their licenses, plus platform-specific ones."""
    out = run_tool([sys.executable, "-m", "piplicenses", "--format=json", "--with-urls"], ROOT)
    if out is None:
        raise SystemExit("pip-licenses failed; run `uv sync --all-extras` first")
    found = parse_pip_licenses(out, runtime_names())
    names = {normalize_name(p.name) for p in found}
    return found + [p for p in PLATFORM_PACKAGES if normalize_name(p.name) not in names]


def render_table(packages: list[Package]) -> str:
    """A markdown table, one row per package."""
    rows = [f"| {p.name} | {p.version} | {p.license} | {p.url} |" for p in packages]
    return "\n".join([GENERATED_NOTE, "", TABLE_HEADER, *rows])


def replace_section(text: str, heading: str, body: str) -> str:
    """Replace everything under `heading` up to the next `## ` heading, keeping the rest verbatim."""
    pattern = re.compile(rf"(^{re.escape(heading)}\n)(.*?)(?=^## |\Z)", re.MULTILINE | re.DOTALL)
    if not pattern.search(text):
        raise SystemExit(f"{LICENSES_FILE.name} has no '{heading}' section")
    return pattern.sub(lambda m: f"{m.group(1)}\n{body}\n\n", text, count=1)


def section_names(text: str, heading: str) -> set[str]:
    """Normalized package names in the first column of the table under `heading`."""
    match = re.search(rf"^{re.escape(heading)}\n(.*?)(?=^## |\Z)", text, re.MULTILINE | re.DOTALL)
    if not match:
        return set()
    cells = (ln.split("|")[1].strip() for ln in match.group(1).splitlines() if ln.startswith("| "))
    return {normalize_name(c) for c in cells if c and c != "Package"}


def is_denied(license_text: str) -> bool:
    """True when the license matches the denylist."""
    return any(p.search(license_text) for p in DENY_PATTERNS)


def find_problems(packages: list[Package], documented: set[str], label: str) -> list[str]:
    """Missing rows, unknown licenses, and denied licenses for one package group."""
    problems: list[str] = []
    for pkg in packages:
        key = normalize_name(pkg.name)
        if key not in documented:
            problems.append(f"{label}: {pkg.name} {pkg.version} has no entry in {LICENSES_FILE.name}")
        if pkg.license in (UNKNOWN, ""):
            problems.append(f"{label}: {pkg.name} {pkg.version} has an unknown license")
        elif is_denied(pkg.license) and key not in ALLOWLIST:
            problems.append(f"{label}: {pkg.name} {pkg.version} uses denied license '{pkg.license}'")
    return problems


def check(text: str, py: list[Package], npm: list[Package]) -> list[str]:
    """All --check problems for the file text and the two package groups."""
    return find_problems(py, section_names(text, PY_HEADING), "python") + find_problems(
        npm, section_names(text, NPM_HEADING), "npm"
    )


def generate(text: str, py: list[Package], npm: list[Package]) -> str:
    """The file text with both generated sections rewritten."""
    text = replace_section(text, PY_HEADING, render_table(py))
    return replace_section(text, NPM_HEADING, render_table(npm))


def main(argv: list[str] | None = None) -> int:
    """Entry point. Returns the process exit code."""
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true", help="verify instead of writing")
    args = parser.parse_args(argv)
    text = LICENSES_FILE.read_text(encoding="utf-8")
    py, npm = python_packages(), all_npm_packages()
    if args.check:
        problems = check(text, py, npm)
        for problem in problems:
            print(f"FAIL  {problem}")
        print(f"{len(py)} python and {len(npm)} npm packages checked, {len(problems)} problem(s)")
        return 1 if problems else 0
    LICENSES_FILE.write_text(generate(text, py, npm), encoding="utf-8")
    print(f"wrote {len(py)} python and {len(npm)} npm packages to {LICENSES_FILE.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
