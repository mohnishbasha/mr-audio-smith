#!/usr/bin/env python3
"""Generate docs/reference/cli.md from the Typer app (walks the click command tree).

Usage: gen-cli-docs.py [--check]   (--check exits 1 when the file is stale)
"""

import sys
from pathlib import Path
from typing import Any

import typer.main

from audio_smith.cli import app
from audio_smith.errors import (
    AudioSmithError,
    ConsentError,
    ExtractError,
    FetchError,
    LLMError,
    MasteringError,
    PreflightError,
    ScriptInvalidError,
    SynthesisError,
    UsageError,
)

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "reference" / "cli.md"
PROG = "mr-audio-smith"
ERRORS: list[type[AudioSmithError]] = [
    AudioSmithError,
    UsageError,
    PreflightError,
    ExtractError,
    FetchError,
    ScriptInvalidError,
    LLMError,
    SynthesisError,
    MasteringError,
    ConsentError,
]


def walk(cmd: Any, path: list[str]) -> list[tuple[list[str], Any]]:
    """Return (path, command) for cmd and every nested subcommand, in declaration order."""
    found: list[tuple[list[str], Any]] = [(path, cmd)]
    subcommands = getattr(cmd, "commands", None)
    if subcommands:
        for name, sub in subcommands.items():
            found.extend(walk(sub, [*path, name]))
    return found


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _type_name(param: Any) -> str:
    if param.param_type_name == "option" and param.is_flag:
        return "flag"
    return str(param.type.name).lower()


def _default(param: Any) -> str:
    if param.param_type_name == "option" and not param.is_flag and param.default is not None:
        return f"`{param.default}`"
    return ""


def _usage(cmd: Any, path: list[str]) -> str:
    ctx = cmd.context_class(cmd, info_name=" ".join([PROG, *path]))
    usage = str(cmd.get_usage(ctx)).removeprefix("Usage: ").strip()
    return usage.replace("{", "<").replace("}", ">")


def render_command(path: list[str], cmd: Any) -> list[str]:
    depth = min(len(path) + 2, 4)
    title = " ".join([PROG, *path])
    out = [f"{'#' * depth} `{title}`", ""]
    help_text = (cmd.help or "").strip()
    if help_text:
        out += [help_text, ""]
    out += ["```text", _usage(cmd, path), "```", ""]
    args = [p for p in cmd.params if p.param_type_name == "argument"]
    opts = [p for p in cmd.params if p.param_type_name == "option" and "--help" not in p.opts]
    if args:
        out += ["| Argument | Type | Required | Description |", "|---|---|---|---|"]
        for a in args:
            req = "yes" if a.required else "no"
            out.append(f"| `{a.name}` | {_type_name(a)} | {req} | {_cell(getattr(a, 'help', None) or '')} |")
        out.append("")
    if opts:
        out += ["| Option | Type | Default | Required | Description |", "|---|---|---|---|---|"]
        for o in opts:
            names = ", ".join(f"`{n}`" for n in [*o.opts, *o.secondary_opts])
            req = "yes" if o.required else "no"
            out.append(f"| {names} | {_type_name(o)} | {_default(o)} | {req} | {_cell(o.help or '')} |")
        out.append("")
    return out


def render() -> str:
    root: Any = typer.main.get_command(app)
    commands = walk(root, [])
    lines = [
        "# CLI reference",
        "",
        "This page is generated by `scripts/gen-cli-docs.py` from the command tree. Do not edit it by hand;",
        "run `uv run python scripts/gen-cli-docs.py` after changing a command.",
        "",
        "## Global options",
        "",
        "| Option | Description |",
        "|---|---|",
    ]
    for p in root.params:
        if p.param_type_name == "option" and "--help" not in p.opts:
            lines.append(
                f"| {', '.join(f'`{n}`' for n in p.opts)} | {_cell(getattr(p, 'help', None) or '')} |"
            )
    lines += ["", "## Commands", ""]
    for path, cmd in commands[1:]:
        lines += render_command(path, cmd)
    lines += [
        "## Exit codes",
        "",
        "Every failure is a typed error with a code, a stage, and an actionable hint.",
        "Stack traces appear only with `--debug`.",
        "",
        "| Exit code | Error class | Code | Stage |",
        "|---|---|---|---|",
    ]
    for err in ERRORS:
        lines.append(f"| {err.exit_code} | `{err.__name__}` | `{err.code}` | `{err.stage}` |")
    lines += ["", "Exit code 0 means success. `site` exits 6 when any page failed.", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        return 0 if TARGET.read_text(encoding="utf-8") == text else 1
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
